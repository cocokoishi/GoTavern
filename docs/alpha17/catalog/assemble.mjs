#!/usr/bin/env node
// Deterministic assembly of docs/alpha17/niche-scenario-catalog.md from docs/alpha17/catalog/NN-*.md.
// - concatenates parts in the fixed order below (00-index first),
// - recomputes the deduplicated scenario count from the assembled text (unique IDs, domain prefixes),
// - writes UTF-8 **without BOM** with a header that states the recomputed counts,
// - exits non-zero if the catalogue has fewer than 150 unique scenario IDs.
//
// Usage: node docs/alpha17/catalog/assemble.mjs [--check]
//   --check  assemble and verify only; do not write the output file.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const catalogDir = here;
const outPath = join(root, 'docs', 'alpha17', 'niche-scenario-catalog.md');

// Fixed part order. Adding a part requires editing this list (fail-closed: a missing part is an error).
const PARTS = [
  '00-index.md',
  '01-fs.md',
  '02-data.md',
  '03-write.md',
  '04-http.md',
  '05-provider.md',
  '06-sse-stream.md',
  '07-prompt.md',
  '08-ext-concurrency.md',
  '09-security.md',
  '10-cli.md',
  '11-perf-cache.md',
];

const DOMAINS = {
  FS: 'filesystem', DATA: 'data/JSON', WRITE: 'persistent writes', HTTP: 'HTTP surface',
  PROVIDER: 'provider transport', SSE: 'SSE', STREAM: 'streaming', PROMPT: 'prompt/request',
  EXT: 'extensions', CONC: 'concurrency', SEC: 'security', CLI: 'CLI/installer/OS',
  PERF: 'performance', CACHE: 'cache',
};

const checkOnly = process.argv.includes('--check');
const parts = [];
for (const name of PARTS) {
  let text;
  try {
    text = readFileSync(join(catalogDir, name), 'utf8');
  } catch (err) {
    console.error(`assemble: missing part ${name}: ${err.message}`);
    process.exit(2);
  }
  if (text.charCodeAt(0) === 0xfeff) {
    console.error(`assemble: ${name} starts with a BOM; parts must be UTF-8 without BOM`);
    process.exit(2);
  }
  parts.push({ name, text: text.replace(/\r\n/g, '\n') });
}

const body = parts.map(p => p.text.trimEnd()).join('\n\n---\n\n') + '\n';

// Unique scenario IDs: table rows whose FIRST cell is a domain ID. Only the DOMAIN parts (01+) are counted;
// the index part (00) contains a dedup-example table that legitimately mentions IDs as prose.
const idRe = /^\|\s*([A-Z]{2,})-(\d{3})\s*\|/;
const seen = new Map();
const perDomain = new Map();
const scenarioBody = parts.slice(1).map(p => p.text).join('\n');
for (const line of scenarioBody.split('\n')) {
  const m = idRe.exec(line);
  if (!m) continue;
  const id = `${m[1]}-${m[2]}`;
  if (seen.has(id)) {
    console.error(`assemble: DUPLICATE scenario id ${id}`);
    process.exit(2);
  }
  seen.set(id, true);
  perDomain.set(m[1], (perDomain.get(m[1]) || 0) + 1);
}

const total = seen.size;
const domains = Object.keys(DOMAINS)
  .filter(prefix => perDomain.has(prefix))
  .map(prefix => `${prefix}=${perDomain.get(prefix)}`)
  .join(', ');

const header = [
  '# alpha.17 niche scenario catalogue',
  '',
  'Status: PROPOSED',
  '',
  `Assembled deterministically by \`docs/alpha17/catalog/assemble.mjs\` from ${parts.length} part files in`,
  '`docs/alpha17/catalog/`. **Do not edit this file directly**; edit the part and re-run the assembler.',
  '',
  `- deduplicated scenarios: **${total}** (unique stable IDs, recomputed by the assembler, target >= 150)`,
  `- per domain: ${domains}`,
  `- parts: ${PARTS.join(', ')}`,
  `- source parts bytes: ${parts.map(p => `${p.name}:${Buffer.byteLength(p.text, 'utf8')}`).join(', ')}`,
  '',
  'Status legend: PROPOSED/COVERED/DESIGNED/UNEXECUTED are defined in the index part (section 3). COVERED',
  'means "a dedicated test exists and was grep-verified", never "it ran"; no row in this catalogue is',
  'EXECUTED, because execution evidence belongs to `docs/alpha17/new-test-evidence.md` and CI artefacts.',
  '',
  '---',
  '',
].join('\n');

const out = header + body;
if (total < 150) {
  console.error(`assemble: only ${total} unique scenarios; target is >= 150`);
  process.exit(1);
}
if (!checkOnly) {
  writeFileSync(outPath, out, 'utf8');
}
if (out.charCodeAt(0) === 0xfeff) {
  console.error('assemble: assembled document starts with a BOM (write failed the encoding check)');
  process.exit(2);
}
console.log(JSON.stringify({
  output: outPath,
  checkOnly,
  parts: parts.length,
  total,
  perDomain: Object.fromEntries(perDomain),
  bytes: Buffer.byteLength(out, 'utf8'),
  firstByteHex: [...Buffer.from(out, 'utf8').subarray(0, 3)].map(b => b.toString(16).padStart(2, '0')).join(' '),
}, null, 2));
