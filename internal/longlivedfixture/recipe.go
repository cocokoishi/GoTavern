// ScenarioTiers are the plan's size tiers, smallest first.
var ScenarioTiers = []string{"small", "medium", "full", "stress"}

// ScenarioTierBounds are the declared resource bounds of each tier. They are DECLARATIONS a consumer can check
// against a recipe's preboot census and a run's observed cost; nothing here silently admits a larger tree into a
// smaller tier.
type ScenarioTierBounds struct {
	MaxFiles      int
	MaxBytes      int64
	MaxOperations int
	MaxSeeds      int
}

