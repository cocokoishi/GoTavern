package longlivedfixture

// THE E-SERIES SEEDED SCENARIO RECIPE (alpha.16 M1, plan section 3; execution-plan sections 3-4).
//
// WHAT THIS ADDS, AND WHY IT IS NOT A THIRD FIXTURE FRAMEWORK.
//
// alpha.16 already has two corpora and one shared schema (`corpus_schema.go`) plus one OPTIONAL scenario block
// (`scenario.go`). The plan asks for a deterministic scenario FACTORY whose recipes declare seed, environment
// class, tier, users, extension points, planned operations, declared faults, expected observables and the
// canonical SHA-256 of the preboot tree -- storing the recipe and manifest, never megabytes of generated
// content. This file is that layer, composed from the machinery that already exists:
//
//   - the tree identity is the SHARED schema's identity: `SeededRecipe.Preboot.TreeSHA256` is computed with the
//     same canonical formula `BuildCorpusSchema` uses (`<sha256>  <path>\n`, sorted), so a recipe describes a
//     tree the existing verifier/reader already understands;
//   - the recipe's counters/operations/faults/observables/bounds reuse `ScenarioRecipe`, `ScenarioAction`,
//     `ScenarioExtension` and `ScenarioResourceBounds` rather than declaring parallel types;
//   - the generated environment is walked by `BuildCorpusSchema` in the tests, so a recipe cannot describe a
//     tree the shared schema cannot read.
//
// WHY THE E-SERIES ENVIRONMENT DOES NOT CARRY A `scenario` BLOCK. The existing block's replay-command rule
// binds a tree to one of the two EXISTING generators (`go run ./cmd/build-longlived` or
// `node tools/build-longlived-corpus.mjs`). This environment is generated by the qualification lane itself, so
// claiming either generator would be a false identity. Adding a third generator identity to the block (and its
// JS mirror) would be exactly the incompatible extension the plan forbids. The recipe document is therefore a
// SEPARATE, independently versioned artifact that WRAPS the shared schema identity and reuses the shared recipe
// types; the corpus schema itself (and its Go/JS field-inventory drift gate) is untouched, which is what proves
// backward compatibility: every existing consumer still reads the v1 shape exactly as before.
//
// BACKWARD-COMPATIBLE READ. `schemaVersion` 2 is current and requires `tier` and `extensionPoints`.
// `schemaVersion` 1 is the pre-tier shape and is still accepted: a missing `tier` resolves to the documented
// legacy default ("small") and missing `extensionPoints` are derived from the recipe's own counts. A field that
// is unknown at the reader's version is refused by name, so a newer manifest is visible rather than silently
// misread.
//
// DETERMINISM. Nothing here reads a clock, a random source, the environment or the target directory. A recipe is
// a pure function of its seed, and the generated bytes are pure functions of the seed and the user handle.

