// SeededEnvironment is a generated multi-seed preboot tree plus the shared schema that describes it.
type SeededEnvironment struct {
	Root   string
	Seeds  []int64
	Users  int
	Schema *CorpusSchema
}

// BuildSeededEnvironment writes the deterministic preboot tree for a seed batch into dataRoot (which must be
// empty or absent), then walks it with the SHARED schema builder. The returned schema is the environment's
// identity; the recipe layer's own preboot digests are canonical digests over the same formula.
func BuildSeededEnvironment(dataRoot string, seeds []int64, users int) (*SeededEnvironment, error) {
	if users != StateMachineUserCount {
		return nil, fmt.Errorf("the E06 state-machine environment is %d users, got %d", StateMachineUserCount, users)
	}
	if len(seeds) == 0 {
		return nil, fmt.Errorf("a seeded environment needs at least one seed")
	}
	files, err := seededEnvironmentFiles(seeds, users)
	if err != nil {
		return nil, err
	}
	for relative, body := range files {
		target := filepath.Join(dataRoot, filepath.FromSlash(relative))
		if err := os.MkdirAll(filepath.Dir(target), 0o777); err != nil {
			return nil, err
		}
		if err := os.WriteFile(target, body, 0o600); err != nil {
			return nil, err
		}
	}
	manifest := seededManifest(seeds, users, files)
	spec := Spec{Seed: seeds[0]}
	schema, err := BuildCorpusSchema(dataRoot, spec, manifest, "e-series-state-machine")
	if err != nil {
		return nil, err
	}
	return &SeededEnvironment{Root: dataRoot, Seeds: append([]int64{}, seeds...), Users: users, Schema: schema}, nil
}

// seededManifest constructs the builder manifest the shared schema derives its declared counts from.
func seededManifest(seeds []int64, users int, files map[string][]byte) *Manifest {
	manifest := &Manifest{Seed: seeds[0], Files: map[string]string{}}
	for relative, body := range files {
		manifest.Files[relative] = digest(body)
	}
	for _, seed := range seeds {
		handle := SeededSeedUser(seed)
		stem := "E_" + strconv.FormatInt(seed, 10)
		manifest.Characters = append(manifest.Characters, Character{Avatar: stem + ".png", Name: stem, Spec: "chara_card_v3"})
		manifest.Chats = append(manifest.Chats, Chat{
			Path:      path.Join(handle, "chats", stem, "PREBOOT.jsonl"),
			Character: stem,
			Messages:  seededPrebootMessages,
		})
		manifest.Worlds = append(manifest.Worlds, World{File: path.Join(handle, "worlds", stem+".json"), Entries: 1})
		manifest.Presets = append(manifest.Presets, stem)
	}
	sort.Strings(manifest.Presets)
	return manifest
}

// seededPrebootMessages is the number of messages in a seed's preboot chat.
const seededPrebootMessages = 3

// seededEnvironmentFiles is the single generator: it returns every file of a preboot tree as
// path -> bytes. The single-seed canonical digest and the batch tree both come from this function, so they
// cannot describe different environments.
func seededEnvironmentFiles(seeds []int64, users int) (map[string][]byte, error) {
	handles := StateMachineUserHandles()
	if users != len(handles) {
		return nil, fmt.Errorf("user count %d does not match the %d declared handles", users, len(handles))
	}
	files := map[string][]byte{}
	for index, handle := range handles {
		settings, err := json.MarshalIndent(map[string]any{
			"username":       handle,
			"e_series_users": users,
			"e_series_env":   RecipeEnvironmentClass,
			"persona":        "E-series synthetic persona",
		}, "", "  ")
		if err != nil {
			return nil, err
		}
		files[path.Join(handle, "settings.json")] = settings
		record, err := seededStorageRecord(handle, index == 0)
		if err != nil {
			return nil, err
		}
		files[path.Join("_storage", seededStorageFilename("user:"+handle))] = record
	}
	for _, seed := range seeds {
		if seed <= 0 {
			return nil, fmt.Errorf("seed %d is not positive", seed)
		}
		handle := SeededSeedUser(seed)
		paths := seededSeedArtifactPaths(seed, handle)
		chat := seededPrebootChat(seed)
		card, err := seededCardPNG(seed)
		if err != nil {
			return nil, err
		}
		world, err := json.MarshalIndent(map[string]any{
			"entries": map[string]any{
				"0": map[string]any{
					"uid": 0, "key": []any{"E_WORLD_KEY_" + strconv.FormatInt(seed, 10)},
					"keysecondary": []any{}, "comment": "seeded world entry", "content": "E_WORLD_" + strconv.FormatInt(seed, 10),
					"constant": false, "selective": true, "order": 100, "disable": false,
				},
			},
		}, "", "  ")
		if err != nil {
			return nil, err
		}
		preset, err := json.MarshalIndent(map[string]any{
			"temperature": 1.0, "openai_max_tokens": 256, "stream_openai": true,
			"e_series_seed": seed,
			"prompts": []any{map[string]any{
				"identifier": "E_PRESET_" + strconv.FormatInt(seed, 10), "name": "seeded preset block",
				"role": "system", "content": "E_PRESET_" + strconv.FormatInt(seed, 10), "marker": true,
			}},
		}, "", "  ")
		if err != nil {
			return nil, err
		}
		files[paths["chat"]] = chat
		files[paths["unknown-file"]] = seededUnknownFile(seed)
		files[paths["card"]] = card
		files[paths["world-book"]] = world
		files[paths["preset"]] = preset
	}
	return files, nil
}

// seededStorageRecord renders the node-persist record the product's own storage reader expects. It mirrors the
// shape `startup.SetNodePersistRecord` writes: {"key":<json string>,"value":<json value>}. The created
// timestamp is FIXED so the tree is deterministic; a real install would have its own, and nothing in the
// environment asserts against this value.
func seededStorageRecord(handle string, admin bool) ([]byte, error) {
	value := struct {
		Handle   string `json:"handle"`
		Name     string `json:"name"`
		Created  int64  `json:"created"`
		Password string `json:"password"`
		Admin    bool   `json:"admin"`
		Enabled  bool   `json:"enabled"`
		Salt     string `json:"salt"`
	}{
		Handle:   handle,
		Name:     "E-series " + handle,
		Created:  1735689600000,
		Password: "",
		Admin:    admin,
		Enabled:  true,
		Salt:     "",
	}
	valueBytes, err := json.Marshal(value)
	if err != nil {
		return nil, err
	}
	keyBytes, err := json.Marshal("user:" + handle)
	if err != nil {
		return nil, err
	}
	record := make([]byte, 0, len(keyBytes)+len(valueBytes)+18)
	record = append(record, `{"key":`...)
	record = append(record, keyBytes...)
	record = append(record, `,"value":`...)
	record = append(record, valueBytes...)
	record = append(record, '}')
	return record, nil
}

// seededStorageFilename is node-persist's sha256(key) filename, the same rule startup/storeFilename uses.
func seededStorageFilename(key string) string {
	sum := sha256.Sum256([]byte(key))
	return hex.EncodeToString(sum[:])
}

// seededPrebootChat writes the seed's pre-existing chat history as pinned JSONL: one message object per line,
// ordered, with the seed and index in the text so a load can prove order rather than count.
func seededPrebootChat(seed int64) []byte {
	stem := strconv.FormatInt(seed, 10)
	var buffer bytes.Buffer
	for index := 0; index < seededPrebootMessages; index++ {
		role := "user"
		name := "E-series user"
		if index%2 == 1 {
			role = "assistant"
			name = "E_" + stem
		}
		record, err := json.Marshal(map[string]any{
			"name":      name,
			"is_user":   role == "user",
			"is_system": false,
			"send_date": "2026-11-06T00:00:00.000Z",
			"mes":       "PREBOOT_" + stem + "_" + strconv.Itoa(index),
			"extra":     map[string]any{"e_series_seed": seed, "e_series_index": index},
		})
		if err != nil {
			panic("seededPrebootChat: " + err.Error())
		}
		buffer.Write(record)
		buffer.WriteByte('\n')
	}
	return buffer.Bytes()
}

// seededUnknownFile is a binary file the product must never rewrite (AGENTS.md 28). It is invalid UTF-8 and
// carries a NUL on purpose, so the schema classifier calls it `binary` rather than quietly treating it as text.
func seededUnknownFile(seed int64) []byte {
	stem := strconv.FormatInt(seed, 10)
	body := []byte{0x00, 0x01, 0xfe, 0xff, 0x02}
	body = append(body, []byte("E_UNKNOWN_"+stem)...)
	body = append(body, 0x00)
	return body
}

// seededCardPNG writes a small deterministic PNG card. It is a valid image (so the avatar/thumbnail routes can
// read it) with the seed encoded in the pixels and the card name, so two seeds never produce the same bytes.
func seededCardPNG(seed int64) ([]byte, error) {
	picture := image.NewRGBA(image.Rect(0, 0, 8, 12))
	for y := 0; y < 12; y++ {
		for x := 0; x < 8; x++ {
			picture.Set(x, y, color.RGBA{R: uint8(seed), G: uint8(x), B: uint8(y), A: 255})
		}
	}
	var encoded bytes.Buffer
	if err := png.Encode(&encoded, picture); err != nil {
		return nil, err
	}
	return encoded.Bytes(), nil
}

// canonicalSeededTree computes the SHARED schema's canonical tree digest (and the class census) from an
// in-memory file map, without writing the tree. The formula is the one BuildCorpusSchema uses for a walked tree:
// sha256 over sorted "<sha256>  <path>\n" lines, excluding the governance manifest names at the root.
func canonicalSeededTree(files map[string][]byte) (SchemaTree, map[string]int) {
	relativePaths := make([]string, 0, len(files))
	filesSHA := make(map[string]string, len(files))
	classes := map[string]int{}
	var totalBytes int64
	for relative, body := range files {
		if !strings.Contains(relative, "/") && CorpusSchemaMetadataNames[relative] {
			continue
		}
		relativePaths = append(relativePaths, relative)
		filesSHA[relative] = digest(body)
		totalBytes += int64(len(body))
		classes[classifyCorpusPath(relative, body)]++
	}
	sort.Strings(relativePaths)
	sum := sha256.New()
	for _, relative := range relativePaths {
		fmt.Fprintf(sum, "%s  %s\n", filesSHA[relative], relative)
	}
	return SchemaTree{SHA256: hex.EncodeToString(sum.Sum(nil)), Files: len(relativePaths), Bytes: totalBytes}, classes
}
