// RecipeExtensionPoints names the four content classes a scenario may extend, explicitly, because "cards: 3" in
// a count and "the card extension point is exercised" are different claims. The counts must agree with the
// nested recipe's own counters; the reader enforces that.
type RecipeExtensionPoints struct {
	Cards      int `json:"cards"`
	Chats      int `json:"chats"`
	WorldBooks int `json:"worldBooks"`
	Presets    int `json:"presets"`
	Extensions int `json:"extensions"`
}

// RecipePreboot is the canonical identity of the generated preboot tree plus the per-role digests the driver
// uses to prove the executed environment is the one the recipe describes. `TreeSHA256` is the shared schema's
// own canonical tree digest over the data-root tree; `Artifacts` maps a role ("chat", "unknown-file", "card",
// "world-book", "preset") to that artifact's SHA-256.
type RecipePreboot struct {
	CorpusSchema        string            `json:"corpusSchema"`
	CorpusSchemaVersion int               `json:"corpusSchemaVersion"`
	TreeSHA256          string            `json:"treeSha256"`
	Files               int               `json:"files"`
	Bytes               int64             `json:"bytes"`
	Classes             map[string]int    `json:"classes"`
	Artifacts           map[string]string `json:"artifacts"`
}

// SeededRecipe is one deterministic scenario recipe: a pure function of its seed. It is data-light: names,
// counters, digests and the operation plan, never the generated content.
type SeededRecipe struct {
	Schema           string                 `json:"schema"`
	SchemaVersion    int                    `json:"schemaVersion"`
	Seed             string                 `json:"seed"`
	EnvironmentClass string                 `json:"environmentClass"`
	Tier             string                 `json:"tier,omitempty"`
	ExtensionPoints  *RecipeExtensionPoints `json:"extensionPoints,omitempty"`
	Recipe           ScenarioRecipe         `json:"recipe"`
	Preboot          RecipePreboot          `json:"preboot"`
}

// RecipeIssue is one named refusal. The name is the stable assertion a test asserts on.
type RecipeIssue struct {
	Name   string
	Detail string
}

func (issue RecipeIssue) String() string {
	if issue.Detail == "" {
		return issue.Name
	}
	return issue.Name + ": " + issue.Detail
}

// RecipeValidationError carries every named issue of a refused recipe.
type RecipeValidationError struct {
	Source string
	Issues []RecipeIssue
}

func (e *RecipeValidationError) Error() string {
	names := make([]string, 0, len(e.Issues))
	for _, issue := range e.Issues {
		names = append(names, issue.String())
	}
	return fmt.Sprintf("seeded recipe %s was refused: %s", e.Source, strings.Join(names, ", "))
}

// Names returns the refused assertion names, deduplicated and sorted.
func (e *RecipeValidationError) Names() []string {
	seen := map[string]bool{}
	names := make([]string, 0, len(e.Issues))
	for _, issue := range e.Issues {
		if seen[issue.Name] {
			continue
		}
		seen[issue.Name] = true
		names = append(names, issue.Name)
	}
	sort.Strings(names)
	return names
}

