// BuildSeededRecipe derives the recipe for one seed. Every value is derived from the generated bytes: the
// preboot digest is the canonical digest of the tree `seededEnvironmentFiles` produces for this seed alone, and
// the artifact digests are that tree's own file digests. No value is hand-typed.
func BuildSeededRecipe(seed int64) (*SeededRecipe, error) {
	if seed <= 0 {
		return nil, fmt.Errorf("a seeded recipe needs a positive seed, got %d", seed)
	}
	files, err := seededEnvironmentFiles([]int64{seed}, StateMachineUserCount)
	if err != nil {
		return nil, err
	}
	tree, classes := canonicalSeededTree(files)
	assignedUser := StateMachineUserHandles()[seedUserIndex(seed)]
	artifacts := map[string]string{}
	for role, relative := range seededSeedArtifactPaths(seed, assignedUser) {
		body, present := files[relative]
		if !present {
			return nil, fmt.Errorf("the generated environment for seed %d is missing its %s at %s", seed, role, relative)
		}
		artifacts[role] = digest(body)
	}
	operations := append([]string{}, StateMachineOperations...)
	recipe := ScenarioRecipe{
		Users:       StateMachineUserCount,
		Cards:       1,
		Chats:       1,
		Prompts:     1,
		Books:       1,
		Extensions:  []ScenarioExtension{},
		Actions:     operations,
		Faults:      append([]string{}, StateMachineFaults...),
		Observables: append([]string{}, StateMachineObservables...),
		ResourceBounds: ScenarioResourceBounds{
			MaxFiles:            len(files) + 64,
			MaxBytes:            tree.Bytes + (1 << 20),
			MaxProviderRequests: 0,
			MaxWallClockMs:      60000,
		},
	}
	return &SeededRecipe{
		Schema:           RecipeSchemaName,
		SchemaVersion:    RecipeSchemaVersion,
		Seed:             strconv.FormatInt(seed, 10),
		EnvironmentClass: RecipeEnvironmentClass,
		Tier:             "small",
		ExtensionPoints: &RecipeExtensionPoints{
			Cards:      recipe.Cards,
			Chats:      recipe.Chats,
			WorldBooks: recipe.Books,
			Presets:    recipe.Prompts,
			Extensions: len(recipe.Extensions),
		},
		Recipe: recipe,
		Preboot: RecipePreboot{
			CorpusSchema:        RecipePrebootSchemaName,
			CorpusSchemaVersion: RecipePrebootSchemaVersion,
			TreeSHA256:          tree.SHA256,
			Files:               tree.Files,
			Bytes:               tree.Bytes,
			Classes:             classes,
			Artifacts:           artifacts,
		},
	}, nil
}

// MarshalSeededRecipe renders a recipe deterministically (indented, one trailing newline).
func MarshalSeededRecipe(recipe *SeededRecipe) ([]byte, error) {
	if recipe == nil {
		return nil, fmt.Errorf("nil seeded recipe")
	}
	body, err := json.MarshalIndent(recipe, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(body, '\n'), nil
}

// WriteSeededRecipe writes a recipe (0600). The recipe is not part of the tree it describes.
func WriteSeededRecipe(target string, recipe *SeededRecipe) error {
	body, err := MarshalSeededRecipe(recipe)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(target), 0o777); err != nil {
		return err
	}
	return os.WriteFile(target, body, 0o600)
}

// ReadSeededRecipe decodes and validates a recipe. A version-1 document is the backward-compatible path: it may
// omit `tier` (defaulted to "small") and `extensionPoints` (derived from the nested recipe's counters).
func ReadSeededRecipe(body []byte) (*SeededRecipe, error) {
	var top map[string]json.RawMessage
	if err := json.Unmarshal(body, &top); err != nil {
		return nil, &RecipeValidationError{Source: "<bytes>", Issues: []RecipeIssue{{Name: "recipe-not-an-object", Detail: err.Error()}}}
	}
	issues := make([]RecipeIssue, 0)
	addf := func(name string, args ...any) {
		issues = append(issues, RecipeIssue{Name: fmt.Sprintf(name, args...)})
	}

	// Member-name checks first: a typed decode cannot see an unknown member, and silently ignoring one is how
	// two definitions drift.
	allowed := map[string]bool{}
	for _, name := range RecipeFieldNames() {
		allowed[name] = true
	}
	unknown := make([]string, 0)
	for name := range top {
		if !allowed[name] {
			unknown = append(unknown, name)
		}
	}
	sort.Strings(unknown)
	for _, name := range unknown {
		addf("recipe-unknown-field:%s", name)
	}
	required := []string{"schema", "schemaVersion", "seed", "environmentClass", "recipe", "preboot"}
	for _, name := range required {
		if _, present := top[name]; !present {
			addf("recipe-field-missing:%s", name)
		}
	}
	if len(issues) > 0 {
		return nil, &RecipeValidationError{Source: "<bytes>", Issues: issues}
	}

	stripped, err := json.Marshal(top)
	if err != nil {
		return nil, err
	}
	var recipe SeededRecipe
	if err := json.Unmarshal(stripped, &recipe); err != nil {
		return nil, &RecipeValidationError{Source: "<bytes>", Issues: []RecipeIssue{{Name: "recipe-malformed", Detail: err.Error()}}}
	}
	issues = append(issues, validateSeededRecipe(&recipe, top)...)
	if len(issues) > 0 {
		return nil, &RecipeValidationError{Source: "<bytes>", Issues: issues}
	}
	return &recipe, nil
}

func validateSeededRecipe(recipe *SeededRecipe, raw map[string]json.RawMessage) []RecipeIssue {
	issues := make([]RecipeIssue, 0)
	addf := func(name string, args ...any) {
		issues = append(issues, RecipeIssue{Name: fmt.Sprintf(name, args...)})
	}
	if recipe.Schema != RecipeSchemaName {
		addf("recipe-schema:%s", recipe.Schema)
	}
	if recipe.SchemaVersion != RecipeSchemaVersion && recipe.SchemaVersion != RecipeLegacySchemaVersion {
		addf("recipe-schema-version:%d", recipe.SchemaVersion)
	}
	seedValue, err := strconv.ParseInt(recipe.Seed, 10, 64)
	if err != nil || seedValue <= 0 {
		addf("recipe-seed:%s", recipe.Seed)
	}
	if recipe.EnvironmentClass != RecipeEnvironmentClass {
		addf("recipe-environment-class:%s", recipe.EnvironmentClass)
	}
	legacy := recipe.SchemaVersion == RecipeLegacySchemaVersion

	// Tier: required at v2, defaulted at v1 (the documented backward-compatible read).
	if !legacy {
		if _, present := raw["tier"]; !present {
			addf("recipe-tier-required")
		}
	}
	tier := recipe.Tier
	if tier == "" {
		tier = "small"
	}
	if !containsValue(ScenarioTiers, tier) {
		addf("recipe-tier:%s", recipe.Tier)
	} else {
		limit := ScenarioTierLimit[tier]
		if recipe.Preboot.Files > limit.MaxFiles {
			addf("recipe-tier-bounds-files:%d>%d", recipe.Preboot.Files, limit.MaxFiles)
		}
		if recipe.Preboot.Bytes > limit.MaxBytes {
			addf("recipe-tier-bounds-bytes:%d>%d", recipe.Preboot.Bytes, limit.MaxBytes)
		}
		if len(recipe.Recipe.Actions) > limit.MaxOperations {
			addf("recipe-tier-bounds-operations:%d>%d", len(recipe.Recipe.Actions), limit.MaxOperations)
		}
	}
	if recipe.Recipe.Users < 1 {
		addf("recipe-users:%d", recipe.Recipe.Users)
	}
	if len(recipe.Recipe.Actions) == 0 {
		addf("recipe-recipe-actions-empty")
	}
	seenActions := map[string]bool{}
	for index, action := range recipe.Recipe.Actions {
		if strings.TrimSpace(action) == "" {
			addf("recipe-recipe-actions-item-%d", index)
		}
		if seenActions[action] {
			addf("recipe-recipe-actions-duplicate:%s", action)
		}
		seenActions[action] = true
	}
	if len(recipe.Recipe.Observables) == 0 {
		addf("recipe-recipe-observables-empty")
	}
	sortedObservables := append([]string{}, recipe.Recipe.Observables...)
	sort.Strings(sortedObservables)
	if strings.Join(sortedObservables, "\x00") != strings.Join(recipe.Recipe.Observables, "\x00") {
		addf("recipe-recipe-observables-order")
	}
	bounds := recipe.Recipe.ResourceBounds
	if bounds.MaxFiles < 1 || bounds.MaxBytes < 1 || bounds.MaxProviderRequests < 0 || bounds.MaxWallClockMs < 1 {
		addf("recipe-recipe-bounds")
	} else {
		if bounds.MaxFiles < recipe.Preboot.Files {
			addf("recipe-tier-bounds-files:%d>%d", recipe.Preboot.Files, bounds.MaxFiles)
		}
		if bounds.MaxBytes < recipe.Preboot.Bytes {
			addf("recipe-tier-bounds-bytes:%d>%d", recipe.Preboot.Bytes, bounds.MaxBytes)
		}
	}

	// Extension points: required at v2, derived from the nested recipe at v1.
	points := recipe.ExtensionPoints
	if !legacy {
		if _, present := raw["extensionPoints"]; !present {
			addf("recipe-extension-points-required")
		}
	}
	if points == nil {
		points = &RecipeExtensionPoints{
			Cards:      recipe.Recipe.Cards,
			Chats:      recipe.Recipe.Chats,
			WorldBooks: recipe.Recipe.Books,
			Presets:    recipe.Recipe.Prompts,
			Extensions: len(recipe.Recipe.Extensions),
		}
	}
	if points.Cards < 0 || points.Chats < 0 || points.WorldBooks < 0 || points.Presets < 0 || points.Extensions < 0 {
		addf("recipe-extension-points")
	} else {
		if points.Cards != recipe.Recipe.Cards {
			addf("recipe-extension-points-cards:%d!=%d", points.Cards, recipe.Recipe.Cards)
		}
		if points.Chats != recipe.Recipe.Chats {
			addf("recipe-extension-points-chats:%d!=%d", points.Chats, recipe.Recipe.Chats)
		}
		if points.WorldBooks != recipe.Recipe.Books {
			addf("recipe-extension-points-world-books:%d!=%d", points.WorldBooks, recipe.Recipe.Books)
		}
		if points.Presets != recipe.Recipe.Prompts {
			addf("recipe-extension-points-presets:%d!=%d", points.Presets, recipe.Recipe.Prompts)
		}
		if len(recipe.Recipe.Extensions) > 0 && points.Extensions != len(recipe.Recipe.Extensions) {
			addf("recipe-extension-points-extensions:%d!=%d", points.Extensions, len(recipe.Recipe.Extensions))
		}
	}

	preboot := recipe.Preboot
	if preboot.CorpusSchema != RecipePrebootSchemaName || preboot.CorpusSchemaVersion != RecipePrebootSchemaVersion {
		addf("recipe-preboot-schema:%s/v%d", preboot.CorpusSchema, preboot.CorpusSchemaVersion)
	}
	if !recipeSHA256Shape.MatchString(preboot.TreeSHA256) {
		addf("recipe-preboot-tree-sha256")
	}
	if preboot.Files < 1 {
		addf("recipe-preboot-files:%d", preboot.Files)
	}
	if preboot.Bytes < 1 {
		addf("recipe-preboot-bytes:%d", preboot.Bytes)
	}
	if len(preboot.Classes) == 0 {
		addf("recipe-preboot-classes")
	}
	if len(preboot.Artifacts) == 0 {
		addf("recipe-preboot-artifacts-missing")
	}
	artifactNames := make([]string, 0, len(preboot.Artifacts))
	for role := range preboot.Artifacts {
		artifactNames = append(artifactNames, role)
	}
	sort.Strings(artifactNames)
	for _, role := range artifactNames {
		if !recipeSHA256Shape.MatchString(preboot.Artifacts[role]) {
			addf("recipe-preboot-artifact:%s", role)
		}
	}
	return issues
}

// SeededRecipeForSeed is the driver entry point: it returns the recipe for one seed.
func SeededRecipeForSeed(seed int64) (*SeededRecipe, error) {
	return BuildSeededRecipe(seed)
}

// DiffSeededRecipes returns the named differences between two recipes. It is the determinism gate: a
// non-deterministic rebuild or a changed seed must produce at least one difference whose Name is the assertion.
func DiffSeededRecipes(previous, next *SeededRecipe) []SchemaDifference {
	differences := make([]SchemaDifference, 0)
	if previous == nil || next == nil {
		return []SchemaDifference{{Name: "recipe-missing"}}
	}
	if previous.Schema != next.Schema || previous.SchemaVersion != next.SchemaVersion {
		differences = append(differences, SchemaDifference{Name: "recipe-schema", Left: previous.Schema, Right: next.Schema})
	}
	if previous.Seed != next.Seed {
		differences = append(differences, SchemaDifference{Name: "recipe-seed", Left: previous.Seed, Right: next.Seed})
	}
	if previous.EnvironmentClass != next.EnvironmentClass || previous.Tier != next.Tier {
		differences = append(differences, SchemaDifference{Name: "recipe-environment-or-tier", Left: previous.EnvironmentClass + "/" + previous.Tier, Right: next.EnvironmentClass + "/" + next.Tier})
	}
	if previous.Preboot.TreeSHA256 != next.Preboot.TreeSHA256 {
		differences = append(differences, SchemaDifference{Name: "recipe-preboot-tree", Left: previous.Preboot.TreeSHA256, Right: next.Preboot.TreeSHA256})
	}
	if previous.Preboot.Files != next.Preboot.Files || previous.Preboot.Bytes != next.Preboot.Bytes {
		differences = append(differences, SchemaDifference{Name: "recipe-preboot-census"})
	}
	leftActions := strings.Join(previous.Recipe.Actions, "\x00")
	rightActions := strings.Join(next.Recipe.Actions, "\x00")
	if leftActions != rightActions {
		differences = append(differences, SchemaDifference{Name: "recipe-operation-plan"})
	}
	leftFaults := strings.Join(previous.Recipe.Faults, "\x00")
	rightFaults := strings.Join(next.Recipe.Faults, "\x00")
	if leftFaults != rightFaults {
		differences = append(differences, SchemaDifference{Name: "recipe-faults"})
	}
	leftObservables := strings.Join(previous.Recipe.Observables, "\x00")
	rightObservables := strings.Join(next.Recipe.Observables, "\x00")
	if leftObservables != rightObservables {
		differences = append(differences, SchemaDifference{Name: "recipe-observables"})
	}
	leftRoles := make([]string, 0, len(previous.Preboot.Artifacts))
	for role := range previous.Preboot.Artifacts {
		leftRoles = append(leftRoles, role)
	}
	sort.Strings(leftRoles)
	rightRoles := make([]string, 0, len(next.Preboot.Artifacts))
	for role := range next.Preboot.Artifacts {
		rightRoles = append(rightRoles, role)
	}
	sort.Strings(rightRoles)
	if strings.Join(leftRoles, "\x00") != strings.Join(rightRoles, "\x00") {
		differences = append(differences, SchemaDifference{Name: "recipe-preboot-artifact-roles"})
	} else {
		for _, role := range leftRoles {
			if previous.Preboot.Artifacts[role] != next.Preboot.Artifacts[role] {
				differences = append(differences, SchemaDifference{Name: "recipe-preboot-artifact:" + role, Left: previous.Preboot.Artifacts[role], Right: next.Preboot.Artifacts[role]})
			}
		}
	}
	sort.Slice(differences, func(left, right int) bool { return differences[left].Name < differences[right].Name })
	return differences
}

// StateMachineUserHandles is the E06 account list, deterministic and ordered. The first handle is the pinned
// default account so a boot still answers the frontend's default-user assumptions.
func StateMachineUserHandles() []string {
	handles := []string{"default-user"}
	for index := 1; index < StateMachineUserCount; index++ {
		handles = append(handles, fmt.Sprintf("user%02d", index))
	}
	return handles
}

// seededUserIndex maps a seed to its account deterministically.
func seedUserIndex(seed int64) int {
	index := seed % int64(StateMachineUserCount)
	if index < 0 {
		index += int64(StateMachineUserCount)
	}
	return int(index)
}

// SeededSeedUser returns the account handle a seed's operations run as, so a caller does not re-derive it.
func SeededSeedUser(seed int64) string {
	return StateMachineUserHandles()[seedUserIndex(seed)]
}

// seededSeedArtifactPaths maps a role to the data-root-relative path of the artifact for one seed under one
// user. It is the single source of truth for both the generator and the driver.
func seededSeedArtifactPaths(seed int64, handle string) map[string]string {
	stem := "E_" + strconv.FormatInt(seed, 10)
	return map[string]string{
		"chat":         path.Join(handle, "chats", stem, "PREBOOT.jsonl"),
		"unknown-file": path.Join(handle, "user", "files", stem+".bin"),
		"card":         path.Join(handle, "characters", stem+".png"),
		"world-book":   path.Join(handle, "worlds", stem+".json"),
		"preset":       path.Join(handle, "OpenAI Settings", stem+".json"),
	}
}

// SeededSeedArtifactPaths is the exported path map the driver reads to prove the executed environment carries
// exactly the artifacts the recipe declares.
func SeededSeedArtifactPaths(seed int64) map[string]string {
	return seededSeedArtifactPaths(seed, SeededSeedUser(seed))
}

