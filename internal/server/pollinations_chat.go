// POLLINATIONS, chat_completion_source: 'pollinations' (src/endpoints/backends/chat-completions.js:2511).
//
// THREE literals, and the endpoint switch moves the HOST for generate:
//
//	generate:  apiUrl = isAnonymous ? API_POLLINATIONS_ANON : API_POLLINATIONS
//	                  = 'https://text.pollinations.ai/v1' : 'https://gen.pollinations.ai/v1'
//	status:    apiUrl = 'https://gen.pollinations.ai/text'      <-- a THIRD literal, not either of those
//	credential: apiKey = isAnonymous ? 'anonymous' : readSecret(.., SECRET_KEYS.POLLINATIONS, ..)
//
// The credential is therefore not "the secret" as a category: in the anonymous mode the pinned branch sends
// the LITERAL string `anonymous` and never reads the secret, so each mode's scenario asserts whichever
// credential it actually puts on the wire (the fixture records `expectedAuthorizationKey`, which the probe
// verifies against what the provider received).
//
// THE SEED IS ALWAYS PRESENT in the body: `seed: request.body.seed ?? Math.floor(Math.random()*99999999)`.
// The provider-wire harness normalises HEADERS only, so a random value inside a compared body cannot be
// marked without a tooling change (a `tools/lib` change with the pipe() discipline, i.e. not a route lane's
// business). Two consequences, both visible in the tests: every recorded scenario SUPPLIES a seed, so no
// random number is ever written into the fixture, and the random fallback is a LABELLED DERIVATION asserting
// the range and that a supplied seed passes through unchanged.
//
// The non-anonymous fold sets `reasoning_effort` (undefined is dropped by JSON.stringify, so it appears only
// when supplied) and json_schema -> `{type:'json_schema', json_schema:{schema:<value>}}`.

import (
	"math/rand"
	"net/http"
	"sync"

	"github.com/cocokoishi/gotavern/internal/startup"
)

const (
	pinnedPollinationsAPIURL     = "https://gen.pollinations.ai/v1"
	pinnedPollinationsAnonAPIURL = "https://text.pollinations.ai/v1"
	// The status route's literal is NOT either generate literal.
	pinnedPollinationsStatusBase     = "https://gen.pollinations.ai/text"
	pinnedPollinationsSeamEnv        = "GOTAVERN_POLLINATIONS_CHAT_URL"
	pinnedPollinationsAnonSeamEnv    = "GOTAVERN_POLLINATIONS_ANON_CHAT_URL"
	pinnedPollinationsStatusEnv      = "GOTAVERN_POLLINATIONS_STATUS_URL"
	pinnedPollinationsSecretKey      = "api_key_pollinations"
	pinnedPollinationsAnonymousKey   = "anonymous"
	pinnedPollinationsAnonMode       = "anonymous"
	chatCompletionSourcePollinations = "pollinations"
)

// pinnedPollinationsAnonymous reports `pollinations_endpoint === POLLINATIONS_ENDPOINT.ANONYMOUS`. The
// comparison is a strict equality against the string 'anonymous', not a truthiness test.
func pinnedPollinationsAnonymous(body orderedNodeJSON) bool {
	endpoint, exists := body.member("pollinations_endpoint")
	if !exists {
		return false
	}
	text, err := pinnedJSStringValue(endpoint)
	return err == nil && text == pinnedPollinationsAnonMode
}

// pinnedPollinationsBaseURL is the generate literal the mode selects, replaceable only by its own seam.
func pinnedPollinationsBaseURL(anonymous bool) string {
	if anonymous {
		return sdSeamURL(pinnedPollinationsAnonSeamEnv, pinnedPollinationsAnonAPIURL)
	}
	return sdSeamURL(pinnedPollinationsSeamEnv, pinnedPollinationsAPIURL)
}

// pinnedPollinationsStatusURL is `<status literal>/models`, with its own seam because the pinned status
// arm uses a literal outside both generate bases.
func pinnedPollinationsStatusURL() string {
	return sdURLJoin(sdSeamURL(pinnedPollinationsStatusEnv, pinnedPollinationsStatusBase), "/models")
}

// pinnedPollinationsSeed implements `request.body.seed ?? Math.floor(Math.random()*99999999)`. The second
// return value reports whether a seed was supplied, which is what the derivation test asserts on.
func pinnedPollinationsSeed(body orderedNodeJSON) (orderedNodeJSON, bool) {
	if seed, exists := body.member("seed"); exists && !seed.isUndefined() && !seed.isNull() {
		return seed, true
	}
	return orderedNodeJSON{kind: 'v', scalar: float64(pinnedPollinationsRandomSeed())}, false
}

var pollinationsSeedMutex sync.Mutex
var pollinationsSeedSource = rand.New(rand.NewSource(1))

// pinnedPollinationsRandomSeed is `Math.floor(Math.random()*99999999)`: an integer in [0, 99999998]. It is
// generated by this process, never recorded, because a recorded random number differs on the next host.
func pinnedPollinationsRandomSeed() int {
	pollinationsSeedMutex.Lock()
	defer pollinationsSeedMutex.Unlock()
	return pollinationsSeedSource.Intn(99999999)
}

// servePollinationsChatCompletionStatus is the POLLINATIONS arm of the status matrix (:1834): the same
// credential switch with the status literal, and no header of its own.
func (runtime *accountRuntime) servePollinationsChatCompletionStatus(w http.ResponseWriter, request *http.Request, body orderedNodeJSON, directories startup.UserDirectories) {
	errorOnly := nodeObject()
	errorOnly.setMember("error", nodeBool(true))
	var key string
	if pinnedPollinationsAnonymous(body) {
		key = pinnedPollinationsAnonymousKey
	} else {
		keyNode, secretErr := pinnedReadSecret(directories, pinnedPollinationsSecretKey, pinnedSecretID(body))
		if secretErr != nil {
			searchJSON(w, errorOnly)
			return
		}
		text, keyErr := pinnedJSStringValue(keyNode)
		if keyErr != nil {
			searchJSON(w, errorOnly)
			return
		}
		key = text
	}
	reverseProxyTruthy := false
	if reverseProxy, exists := body.member("reverse_proxy"); exists && pinnedJSTruthy(reverseProxy) {
		reverseProxyTruthy = true
	}
	if key == "" && !reverseProxyTruthy {
		pinnedChatCompletionMissingKeyRefusal(w)
		return
	}
	headers := map[string]string{"authorization": "Bearer " + key}
	response, fetchErr := searchFetch(request.Context(), searchRequest{
		Method:  http.MethodGet,
		URL:     pinnedPollinationsStatusURL(),
		Headers: headers,
	})
	if fetchErr != nil {
		searchJSON(w, errorOnly)
		return
	}
	if !sdResponseOK(response) {
		failure := nodeObject()
		failure.setMember("error", nodeBool(true))
		emptyData := nodeObject()
		emptyData.setMember("data", nodeArray())
		failure.setMember("data", emptyData)
		searchJSON(w, failure)
		return
	}
	data, parsed := sdReadJSON(response)
	if !parsed {
		searchJSON(w, errorOnly)
		return
	}
	searchJSON(w, data)
}
