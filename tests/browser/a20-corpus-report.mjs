// a20-corpus-report.mjs -- turn a finalized corpus manifest (a19-corpus-finalize.mjs output) plus the
// builder reports that produced it into the alpha.20 multi-tier report.
//
// The report exists because a tier is judged by COUNTS AND PROVENANCE, not by a file count alone. It
// records, per category, the target, the achieved number, and whether the target was reached; and it
// keeps four provenance layers SEPARATE rather than merging them into one flattering number:
//
//   uiCreated       product resources created through real UI controls (import inputs, editor, panel)
//   uiInteracted    real UI actions recorded in the action logs / round reports (send, swipe, edit, ...)
//   productNative   data persisted by the PRODUCT's own save functions after a UI-initiated action
//                   (the disclosed message split: real sends vs saveChatConditional fill)
//   generatedStress INPUT files generated by the driver for the UI to import (cards, world JSON,
//                   preset JSON). These are not product data and never counted as created resources.
//
// RUN:
//   node tests/browser/a20-corpus-report.mjs --manifest <manifest.json> --out <report.json> \
//     --tier medium [--round-reports a.json,b.json] [--topup <topup.json>] [--messages <message-report.json>] \
//     [--seed <value>]
//
// A target that is not reached is NOT an error here: the report records `reached:false` and the exact
// achieved count, which is the honest boundary the charter asks for.

import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const argv = process.argv.slice(2);
const argument = (name, fallback = null) => {
    const index = argv.indexOf(name);
    return index === -1 ? fallback : argv[index + 1] ?? fallback;
};

const manifestPath = path.resolve(argument('--manifest', ''));
const outPath = path.resolve(argument('--out', ''));
const tier = argument('--tier', 'medium');
const roundReportPaths = (argument('--round-reports', '') ?? '').split(',').map(value => value.trim()).filter(Boolean).map(value => path.resolve(value));
const topupPaths = (argument('--topups', '') ?? '').split(',').map(value => value.trim()).filter(Boolean).map(value => path.resolve(value));
const topupPath = topupPaths[0] ?? (argument('--topup', null) ? path.resolve(argument('--topup')) : null);
const messagesPath = argument('--messages', null) ? path.resolve(argument('--messages')) : null;
const provenancePath = argument('--provenance', null) ? path.resolve(argument('--provenance')) : null;
const gapfillPath = argument('--gapfill', null) ? path.resolve(argument('--gapfill')) : null;
const fillActionsPath = argument('--fill-actions', null) ? path.resolve(argument('--fill-actions')) : null;
const seed = argument('--seed', null);
if (!manifestPath || !outPath) {
    console.error('usage: node a20-corpus-report.mjs --manifest <manifest.json> --out <report.json> [--tier small|medium|large] [--round-reports a,b] [--topup t.json] [--messages m.json] [--seed s]');
    process.exit(2);
}

const TIER_TARGETS = {
    small: {
        characters: 8, worlds: 2, worldEntries: 16, presets: 4, chats: 10, messages: 80, groups: 2,
        personas: 1, quickReplies: 1, regexes: 1,
    },
    medium: {
        characters: 64, worlds: 12, worldEntries: 200, presets: 20, chats: 100, messages: 3000, groups: 8,
        // The charter's medium minimums are the first seven categories; the UI-feature categories only need
        // to be PRESENT with real content, so the target here is the base rounds' own created count, not an
        // invented numeric minimum.
        personas: 2, quickReplies: 2, regexes: 2,
    },
    large: {
        characters: 200, worlds: 30, worldEntries: 800, presets: 50, chats: 500, messages: 20000, groups: 20,
        personas: 5, quickReplies: 5, regexes: 5,
    },
};
const targets = TIER_TARGETS[tier];
if (!targets) { console.error(`a20-corpus-report: unknown tier ${JSON.stringify(tier)}`); process.exit(2); }

async function readJson(file) {
    if (!file) return null;
    try { return JSON.parse(await fs.readFile(file, 'utf8')); } catch { return null; }
}

const manifest = await readJson(manifestPath);
if (!manifest) { console.error(`a20-corpus-report: cannot read manifest ${manifestPath}`); process.exit(1); }
const roundReports = [];
for (const file of roundReportPaths) {
    const report = await readJson(file);
    if (report) roundReports.push({ file: path.basename(file), report });
}
const topup = await readJson(topupPath);
const topups = [];
for (const file of topupPaths) {
    const report = await readJson(file);
    if (report) topups.push({ file: path.basename(file), targets: report.targets ?? null, created: report.created ?? null, measured: report.measured ?? null, steps: report.steps ?? null });
}
const messages = await readJson(messagesPath);
const messageProvenance = await readJson(provenancePath);
const gapfill = await readJson(gapfillPath);
// Chat-creation provenance: count the recorded New Chat ACTIONS from the fill action log. A real UI
// control action is one recorded `new-chat` / `new-chat-ui` record; the product-function volume is the
// recorded `new-chats-product-function` record's `created` count. The disk chat count comes from the
// manifest, and any difference is recorded as an unexplained boundary rather than guessed.
let chatCreation = null;
if (fillActionsPath) {
    try {
        const lines = (await fs.readFile(fillActionsPath, 'utf8')).split('\n').filter(line => line.trim().length > 0);
        const byPhase = {};
        let productFunctionCalls = null;
        for (const line of lines) {
            let record = null;
            try { record = JSON.parse(line); } catch { continue; }
            byPhase[record.phase] = (byPhase[record.phase] ?? 0) + 1;
            if (record.phase === 'new-chats-product-function') productFunctionCalls = record.created ?? productFunctionCalls;
        }
        chatCreation = {
            source: 'fill action log + manifest chat count',
            uiControlChatActions: (byPhase['new-chat'] ?? 0) + (byPhase['new-chat-ui'] ?? 0),
            productFunctionNewChatCalls: productFunctionCalls,
            chatsOnDisk: Number(manifest.counts?.chats ?? 0),
            attribution: 'UI-control-created and product-function-created chats are recorded separately; the disk count is the sum measured by the manifest, and the difference between the recorded actions and the disk count is NOT attributed to a behaviour this probe instrumented (a New Chat call can also persist the outgoing chat), so it is disclosed as a boundary.',
            unexplainedChatFiles: Number(manifest.counts?.chats ?? 0) - ((byPhase['new-chat'] ?? 0) + (byPhase['new-chat-ui'] ?? 0)) - (productFunctionCalls ?? 0),
        };
    } catch { chatCreation = null; }
}

const counts = manifest.counts ?? {};
const seeded = manifest.seeded ?? {};
const achieved = {};
const targetRows = [];
for (const [category, target] of Object.entries(targets)) {
    const created = Number(counts[category] ?? 0);
    const seededCount = Number(seeded[category] ?? 0);
    achieved[category] = created;
    targetRows.push({
        category,
        target,
        achieved: created,
        reached: created >= target,
        shortfall: Math.max(0, target - created),
        seededNotCounted: seededCount,
        note: category === 'worldEntries' ? 'created entries only; the seeded Eldoria book has 4 entries and is excluded from `achieved`' : null,
    });
}
const reached = targetRows.every(row => row.reached);
const boundary = reached ? null : {
    reachedAllTargets: false,
    unmet: targetRows.filter(row => !row.reached).map(row => ({ category: row.category, target: row.target, achieved: row.achieved, shortfall: row.shortfall })),
    reason: argument('--boundary-reason', 'recorded from the measured corpus; no target is claimed reached that the counts do not show'),
};

// UI-interacted: count recorded steps from the round reports (each step is an observed real action).
let uiSteps = 0;
const uiStepFailures = [];
for (const { report } of roundReports) {
    for (const step of report.steps ?? []) {
        uiSteps += 1;
        if (step.ok !== true) uiStepFailures.push({ report: report.round ?? null, name: step.name, detail: step.detail ?? null });
    }
}

// Product-native save split: measured from the persisted JSONL by a20-corpus-provenance.mjs. The
// manifest's own messageSplit is kept only as a cross-check and is NOT used when the byte-derived
// provenance document is supplied (the markers are the stronger observation).
const messageSplit = manifest.messageSplit ?? null;
const productNative = {
    source: messageProvenance
        ? 'a20-corpus-provenance.mjs: derived from the persisted JSONL bytes (markers), not from a builder log'
        : 'manifest.messageSplit (persisted chat/group JSONL records)',
    viaUiTurns: messageProvenance?.counts?.uiTurnMessages ?? messageSplit?.viaUiTurns ?? null,
    viaProductSavePath: messageProvenance?.counts?.productSavePathMessages ?? messageSplit?.viaProductSavePath ?? null,
    viaProductNativeChat: messageProvenance?.counts?.productNativeChatMessages ?? null,
    uiTurnPairs: messageProvenance?.counts?.uiTurnPairs ?? null,
    totalMessages: messageProvenance?.counts?.messages ?? messageSplit ? ((messageSplit?.viaUiTurns ?? 0) + (messageSplit?.viaProductSavePath ?? 0)) : null,
    method: messageProvenance?.method ?? messageSplit?.basis ?? null,
    disclosedCounts: messageProvenance?.disclosed ?? null,
    manifestCrossCheck: messageSplit,
    messageTopupReport: messages ? {
        uiSentMessages: messages.uiSentMessages ?? null,
        savePathMessages: messages.savePathMessages ?? null,
        turnsPerSecond: messages.turnsPerSecond ?? null,
        target: messages.target ?? null,
    } : null,
};

// Groups created through the disclosed product-API fallback are NOT uiCreated; they are counted here.
let productApiGroups = 0;
for (const { report } of roundReports) {
    productApiGroups += Number(report?.counts?.groupsCreatedViaProductApi ?? 0);
}

const report = {
    schema: 'a20-corpus-report-v1',
    kind: 'a20-multi-tier-corpus-report',
    tier,
    generatedAt: new Date().toISOString(),
    pinned: { version: '1.19.0', commit: '06bde939fb1e9c4c8d8641d810f0a916b5bce127' },
    manifest: {
        file: path.basename(manifestPath),
        schema: manifest.schema ?? null,
        treeSha256: manifest.treeSha256 ?? null,
        files: manifest.files ?? null,
        bytes: manifest.bytes ?? null,
    },
    targets: targetRows,
    reachedAllTargets: reached,
    boundary,
    provenance: {
        uiCreated: {
            source: 'manifest.counts minus manifest.seeded (the pinned fresh-install baseline is measured, not assumed)',
            counts,
            seeded,
            note: 'every resource here was produced by a real UI control or by the frontend module function behind that control; the input files the controls consumed are listed under generatedStressOnly',
        },
        uiInteracted: {
            source: 'round reports: one recorded step per real control interaction',
            steps: uiSteps,
            failures: uiStepFailures,
        },
        productNativeSave: {
            ...productNative,
            note: 'messages appended to the page chat model and persisted through the product own save (saveChatConditional) are NOT UI turns; they are disclosed separately and were never hand-written JSONL',
        },
        generatedStressOnly: {
            source: 'driver-generated input files consumed by UI import controls',
            note: 'cards (PNG), world books (JSON), presets (JSON), backgrounds/themes; they are inputs, never counted as created product resources',
            examples: ['writeCardPng', 'writeWorldJson', 'writePresetFile', 'writeThemeFile', 'writePng'],
        },
        chatCreation,
        extensions: gapfill ? {
            source: 'a19-corpus-gapfill.mjs against this corpus (through the pinned wrapper)',
            countsBefore: gapfill.countsBefore ?? null,
            countsAfter: gapfill.countsAfter ?? null,
            extension: gapfill.extension ?? null,
            verbs: gapfill.verbs ?? null,
            steps: gapfill.steps ?? null,
        } : null,
    },
    determinism: {
        seed: seed ?? argument('--seed', 'provider replies are produced by the deterministic recording peer; no wall-clock or random value decides content'),
        replay: 'the driver skips resources that already exist, so a re-run over the same tree is an idempotent replay; a fresh tier run starts from a fresh data root and the manifest digest pins the result',
        actionLogs: manifest.actionLogs ?? null,
    },
    tierEvidence: {
        roundReports: roundReports.map(({ file, report: value }) => ({ file, round: value.round ?? null, ok: value.ok ?? null, steps: (value.steps ?? []).length, counts: value.counts ?? null })),
        topup: topups.length > 0 ? { runs: topups } : (topup ? { targets: topup.targets ?? null, created: topup.created ?? null, measured: topup.measured ?? null, steps: topup.steps ?? null, failures: topup.failures ?? null } : null),
        messageTopup: messages ? { file: path.basename(messagesPath), target: messages.target ?? null, messagesBefore: messages.messagesBefore ?? null, messagesAfter: messages.messagesAfter ?? null } : null,
    },
    honestLimits: [
        'A generated input file is not a user artefact; only the UI import action is the creation provenance for cards/books/presets.',
        'The message split is disclosed, not hidden: the product-save-path share is not UI-originated.',
        'A tier matrix is a corpus, not a real human long-lived directory (GOAL.md section 14 stays NOT MET).',
        'Counts are computed from the finalized tree, never copied from a builder log.',
    ],
};

await fs.mkdir(path.dirname(outPath), { recursive: true });
await fs.writeFile(outPath, `${JSON.stringify(report, null, 2)}\n`, 'utf8');
console.log(`report: ${outPath}`);
console.log(`tier ${tier}: ${reached ? 'all targets reached' : 'targets NOT all reached: ' + boundary.unmet.map(row => `${row.category} ${row.achieved}/${row.target}`).join(', ')}`);
