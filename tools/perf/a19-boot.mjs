#!/usr/bin/env node

// a19-boot: alpha.19 process-level startup / steady-RSS / data-route latency harness.
//
// WHY THIS EXISTS RATHER THAN REUSING scripts/a15-bench-suite.mjs.
// The A15 suite is the right tool for multi-subject paired comparisons, and it stays the tool for those. Its
// readiness poll sleeps 20 ms between attempts, which is fine for a 300 ms..30 s boot and NOT fine for the
// alpha.19 warm-boot row: alpha.18 recorded a 165 ms warm boot, so a 20 ms poll carries up to 12% quantisation
// error and cannot answer "did startup get faster?" honestly. This harness polls with a raw loopback TCP
// connect (no fetch, no connection pool, no 20 ms sleep), so the boot number is the time from spawn to the
// first complete `200` on `GET /version`, measured at 1-2 ms granularity.
//
// WHAT IT MEASURES, per round, over a tree generated by tests/perf/fixturegen (the same deterministic generator
// the A15 suite and internal/server/bench_test.go shapes mirror):
//   cold     spawn -> first `GET /version` 200 on a FRESHLY GENERATED tree (first boot: stats/secret seeding
//            is inside the window, which is what a user's first boot pays);
//   warm     spawn -> first 200 on the SAME tree, booted again after the cold boot has written whatever the
//            first boot writes;
//   ready    one tests/perf/procstat sample at readiness (RSS, PEAK RSS, CPU user+system, method named);
//   data     the first POST to a data route (cold process cache) and the repeats after it (warm), with
//            p50/p95/p99/max over the repeat samples;
//   final    a procstat sample after the requests, so steady RSS/CPU deltas are measured, not inferred.
//
// HONEST LIMITS, repeated into every artifact:
//   - the shared development host is not quiet; every artifact carries --load-label AND a sampled CPU-load
//     series, and absolute milliseconds are comparable only WITHIN one run (the A15 suite states the same);
//   - Windows cannot deliver SIGTERM to a console process, so the stop is abrupt and recorded as such;
//   - Go allocation totals are not observable from outside a process; B/op and allocs/op come from the
//     in-process benchmarks (internal/server/bench_test.go), never from this file;
//   - PEAK RSS is procstat's born-named `PeakWorkingSetSize`/`VmHWM`; a B/op value is NEVER reported as RSS.
//
// USAGE
//   node tools/perf/a19-boot.mjs --binary <gotavern.exe> --scale cards --cards 1000 \
//     --image-bytes 32768 --card-bytes 8192 --rounds 3 --requests 8 --out <artifact.json> \
//     --load-label "quiet: no other lane" --data-route characters
//
// EXIT CODES: 0 measured; 1 a round failed (the failure is named in the artifact); 2 usage/setup failure.

import { spawn, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { createServer, connect } from 'node:net';
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..', '..');

const DATA_ROUTES = {
    characters: { method: 'POST', route: '/api/characters/all', body: '{}' },
    worlds: { method: 'POST', route: '/api/worldinfo/list', body: '{}' },
    settings: { method: 'POST', route: '/api/settings/get', body: '{}' },
    chats: { method: 'POST', route: '/api/characters/chats', body: '{"avatar_url":"A15 Character.png"}' },
};

function usage(message) {
    if (message) console.error(`a19-boot: ${message}\n`);
    console.error(`Usage: node tools/perf/a19-boot.mjs --binary <path> [options]

  --binary <path>          GoTavern binary to boot (required)
  --scale <name>           fixturegen scale (default cards)
  --cards <n>               --image-bytes <n> --card-bytes <n>   passed to fixturegen
  --chats <n>               --chat-bytes <n>                     passed to fixturegen
  --worlds <n>              --world-bytes <n>                    passed to fixturegen
  --rounds <n>             rounds, each generating a fresh tree (default 3)
  --requests <n>           data-route requests per boot, 1 cold + n-1 warm (default 8)
  --data-route <name>      ${Object.keys(DATA_ROUTES).join('|')} (default characters)
  --poll-ms <n>            readiness poll interval (default 2)
  --work-dir <dir>         where generated trees/binary copies live (default <scratch>/a19-boot)
  --out <file>             artifact path (default <work-dir>/a19-boot-<stamp>.json)
  --load-label <text>      what else was running on this host (required for an honest claim)
  --fixturegen <path/--procstat <path>   reuse already-built helpers instead of building them
  --keep-trees             do not delete the generated tree directories
`);
    process.exit(2);
}

function parseArguments(argv) {
    const options = {
        binary: null, scale: 'cards', cards: 100, imageBytes: 4096, cardBytes: 4096,
        chats: 10, chatBytes: 262144, worlds: 50, worldBytes: 32768,
        rounds: 3, requests: 8, dataRoute: 'characters', pollMs: 2,
        workDir: path.join(repoRoot, '..', 'a19-perf', 'boot'),
        out: null, loadLabel: 'unlabelled (shared host; treat absolute ms as within-run only)',
        fixturegen: null, procstat: null, keepTrees: false,
    };
    for (let index = 0; index < argv.length; index += 1) {
        const flag = argv[index];
        const value = () => {
            const next = argv[index + 1];
            if (next === undefined || next.startsWith('--')) usage(`${flag} needs a value`);
            index += 1;
            return next;
        };
        switch (flag) {
            case '--binary': options.binary = path.resolve(value()); break;
            case '--scale': options.scale = value(); break;
            case '--cards': options.cards = Number(value()); break;
            case '--image-bytes': options.imageBytes = Number(value()); break;
            case '--card-bytes': options.cardBytes = Number(value()); break;
            case '--chats': options.chats = Number(value()); break;
            case '--chat-bytes': options.chatBytes = Number(value()); break;
            case '--worlds': options.worlds = Number(value()); break;
            case '--world-bytes': options.worldBytes = Number(value()); break;
            case '--rounds': options.rounds = Number(value()); break;
            case '--requests': options.requests = Number(value()); break;
            case '--data-route': options.dataRoute = value(); break;
            case '--poll-ms': options.pollMs = Number(value()); break;
            case '--work-dir': options.workDir = path.resolve(value()); break;
            case '--out': options.out = path.resolve(value()); break;
            case '--load-label': options.loadLabel = value(); break;
            case '--fixturegen': options.fixturegen = path.resolve(value()); break;
            case '--procstat': options.procstat = path.resolve(value()); break;
            case '--keep-trees': options.keepTrees = true; break;
            case '--help': usage(); break;
            default: usage(`unknown flag ${flag}`);
        }
    }
    if (!options.binary || !fs.existsSync(options.binary)) usage('--binary must name an existing file');
    if (!DATA_ROUTES[options.dataRoute]) usage(`--data-route must be one of ${Object.keys(DATA_ROUTES).join('|')}`);
    if (!(options.rounds >= 1) || !(options.requests >= 1)) usage('--rounds and --requests must be >= 1');
    return options;
}

const options = parseArguments(process.argv.slice(2));

const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));

function gitFacts() {
    const run = args => {
        const result = spawnSync('git', args, { cwd: repoRoot, encoding: 'utf8' });
        return result.status === 0 ? result.stdout.trim() : null;
    };
    return {
        commit: run(['rev-parse', 'HEAD']),
        branch: run(['rev-parse', '--abbrev-ref', 'HEAD']),
        dirty: (run(['status', '--porcelain']) ?? '').length > 0,
    };
}

function sha256File(file) {
    return createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

function binaryVersion(binary) {
    const result = spawnSync(binary, ['version'], { encoding: 'utf8' });
    return result.status === 0 ? (result.stdout.split('\n')[0] ?? '').trim() : null;
}

// Sampled host CPU load: deltas of os.cpus() over an interval. Recorded so a run made while other lanes were
// compiling or driving browsers cannot be quoted as a quiet-host number without the artifact disagreeing.
function cpuSnapshot() {
    let idle = 0;
    let total = 0;
    for (const cpu of os.cpus()) {
        for (const value of Object.values(cpu.times)) total += value;
        idle += cpu.times.idle;
    }
    return { idle, total, at: Date.now() };
}

async function cpuLoadOver(ms) {
    const before = cpuSnapshot();
    await sleep(ms);
    const after = cpuSnapshot();
    const busy = (after.total - before.total) - (after.idle - before.idle);
    const total = after.total - before.total;
    return total > 0 ? Number(((busy / total) * 100).toFixed(1)) : null;
}

function buildHelper(name, source) {
    const directory = path.join(options.workDir, 'bin');
    fs.mkdirSync(directory, { recursive: true });
    const target = path.join(directory, process.platform === 'win32' ? `${name}.exe` : name);
    if (!fs.existsSync(target)) {
        const result = spawnSync('go', ['build', '-trimpath', '-o', target, source], { cwd: repoRoot, encoding: 'utf8' });
        if (result.status !== 0) throw new Error(`go build ${source} failed: ${result.stderr}`);
    }
    return target;
}

function choosePort() {
    return new Promise((resolve, reject) => {
        const server = createServer();
        server.unref();
        server.on('error', reject);
        server.listen(0, '127.0.0.1', () => {
            const { port } = server.address();
            server.close(() => resolve(port));
        });
    });
}

function sampleProcess(pid) {
    const result = spawnSync(options.procstat, ['--pid', String(pid)], { encoding: 'utf8' });
    const text = (result.stdout ?? '').trim();
    if (!text) return { ok: false, error: `procstat exit ${result.status}: ${(result.stderr ?? '').trim()}` };
    try { return JSON.parse(text); } catch { return { ok: false, error: `procstat emitted non-JSON: ${text.slice(0, 200)}` }; }
}

// Raw-socket readiness probe: TCP connect, one request line, first status line. Deliberately not fetch():
// fetch brings DNS, a connection pool and keep-alive bookkeeping into the measured window.
function probeVersion(port, timeoutMs) {
    return new Promise((resolve, reject) => {
        const socket = connect({ host: '127.0.0.1', port });
        let settled = false;
        let received = '';
        const finish = (error, value) => {
            if (settled) return;
            settled = true;
            socket.destroy();
            if (error) reject(error); else resolve(value);
        };
        socket.setTimeout(timeoutMs, () => finish(new Error('timeout')));
        socket.once('error', error => finish(error));
        socket.once('connect', () => {
            socket.write('GET /version HTTP/1.1\r\nHost: 127.0.0.1\r\nConnection: close\r\n\r\n');
        });
        socket.on('data', chunk => {
            received += chunk.toString('latin1');
            const end = received.indexOf('\r\n');
            if (end < 0) return;
            const statusLine = received.slice(0, end);
            const status = Number(statusLine.split(' ')[1]);
            if (Number.isFinite(status)) finish(null, status);
        });
        socket.once('close', () => finish(new Error('closed before a status line')));
    });
}

async function waitForReady(port, ceilingMs, pollMs) {
    const deadline = Date.now() + ceilingMs;
    let last = null;
    while (Date.now() < deadline) {
        try {
            const status = await probeVersion(port, Math.max(250, pollMs * 50));
            if (status === 200) return;
            last = `status ${status}`;
        } catch (error) {
            last = error.message;
        }
        await sleep(pollMs);
    }
    throw new Error(`no 200 on GET /version within ${ceilingMs} ms (last: ${last})`);
}

function startBoot(tree, port, logs) {
    const argv = [
        'start',
        '--port', String(port),
        '--dataRoot', tree.dataRoot,
        '--configPath', tree.configPath,
        '--browserLaunchEnabled', 'false',
        '--listen', 'false',
        '--enableIPv4', 'true',
        '--enableIPv6', 'false',
        '--listenAddressIPv4', '127.0.0.1',
        '--heartbeatInterval', '0',
    ];
    const child = spawn(options.binary, argv, {
        cwd: path.dirname(tree.dataRoot),
        env: { ...process.env, GOMAXPROCS: process.env.GOMAXPROCS ?? '2', GODEBUG: 'gctrace=0' },
        stdio: ['ignore', 'pipe', 'pipe'],
        windowsHide: true,
    });
    child.stdout.on('data', chunk => logs.push(chunk.toString('utf8')));
    child.stderr.on('data', chunk => logs.push(chunk.toString('utf8')));
    return child;
}

async function stopBoot(child) {
    if (!child || child.exitCode !== null) return { mode: 'already-exited' };
    child.kill();
    const exited = await Promise.race([
        new Promise(resolve => child.once('exit', () => resolve(true))),
        sleep(5000).then(() => false),
    ]);
    if (!exited && child.pid) {
        spawnSync('taskkill', ['/PID', String(child.pid), '/T', '/F'], { encoding: 'utf8' });
    }
    return { mode: process.platform === 'win32' ? 'abrupt-windows (TerminateProcess/taskkill)' : 'SIGTERM' };
}

class HttpSession {
    constructor(origin) {
        this.origin = origin;
        this.cookies = new Map();
        this.csrf = null;
    }

    absorb(response) {
        for (const raw of response.headers.getSetCookie?.() ?? []) {
            const pair = raw.split(';')[0];
            const index = pair.indexOf('=');
            if (index > 0) this.cookies.set(pair.slice(0, index).trim(), pair.slice(index + 1).trim());
        }
    }

    cookieHeader() {
        return [...this.cookies.entries()].map(([name, value]) => `${name}=${value}`).join('; ');
    }

    headers(extra = {}) {
        const headers = { ...extra };
        if (this.cookies.size) headers.cookie = this.cookieHeader();
        if (this.csrf) headers['x-csrf-token'] = this.csrf;
        return headers;
    }

    async handshake() {
        const response = await fetch(`${this.origin}/csrf-token`, { signal: AbortSignal.timeout(5000) });
        this.absorb(response);
        const body = await response.text();
        try { this.csrf = JSON.parse(body).token ?? null; } catch { this.csrf = null; }
        if (!this.csrf) this.csrf = 'disabled';
    }

    async request(method, route, body) {
        const started = process.hrtime.bigint();
        const response = await fetch(`${this.origin}${route}`, {
            method,
            headers: this.headers(body === undefined ? {} : { 'content-type': 'application/json' }),
            body: body === undefined ? undefined : body,
            signal: AbortSignal.timeout(600000),
        });
        const bytes = (await response.arrayBuffer()).byteLength;
        this.absorb(response);
        return { status: response.status, bytes, ms: Number(process.hrtime.bigint() - started) / 1e6 };
    }
}

function summarise(values) {
    if (!values.length) return null;
    const sorted = [...values].sort((a, b) => a - b);
    const pick = fraction => sorted[Math.min(sorted.length - 1, Math.max(0, Math.ceil(fraction * sorted.length) - 1))];
    return {
        count: sorted.length,
        min: sorted[0],
        p50: pick(0.5),
        p95: pick(0.95),
        p99: pick(0.99),
        max: sorted[sorted.length - 1],
        median: sorted[Math.floor(sorted.length / 2)],
    };
}

async function measureBoot(tree, label, rounds) {
    const port = await choosePort();
    const origin = `http://127.0.0.1:${port}`;
    const logs = [];
    const started = process.hrtime.bigint();
    const child = startBoot(tree, port, logs);
    const record = { label, origin, pid: child.pid ?? null, samples: [], requests: [], error: null };
    try {
        await waitForReady(port, 120000, options.pollMs);
    } catch (error) {
        record.error = error.message;
        record.logTail = logs.join('').slice(-4000);
        await stopBoot(child);
        record.bootMs = null;
        return record;
    }
    record.bootMs = Number(process.hrtime.bigint() - started) / 1e6;
    record.bootToReadyMs = record.bootMs;
    record.readySample = sampleProcess(child.pid);
    record.samples.push({ at: 'ready', ...record.readySample });

    const session = new HttpSession(origin);
    await session.handshake();
    const route = DATA_ROUTES[options.dataRoute];
    for (let index = 0; index < options.requests; index += 1) {
        const row = await session.request(route.method, route.route, route.body);
        record.requests.push({ index, cache: index === 0 ? 'cold' : 'warm', ...row });
    }
    record.finalSample = sampleProcess(child.pid);
    record.samples.push({ at: 'final', ...record.finalSample });
    record.stop = await stopBoot(child);
    record.logTail = logs.join('').slice(-2000);
    return record;
}

async function main() {
    fs.mkdirSync(options.workDir, { recursive: true });
    if (!options.procstat) options.procstat = buildHelper('a15-procstat', './tests/perf/procstat');
    if (!options.fixturegen) options.fixturegen = buildHelper('a15-fixturegen', './tests/perf/fixturegen');

    const stamp = new Date().toISOString().replace(/[:.]/g, '-');
    const out = options.out ?? path.join(options.workDir, `a19-boot-${stamp}.json`);
    const scaleArgs = [];
    switch (options.scale) {
        case 'cards':
        case 'cards-heavy':
            scaleArgs.push('--cards', String(options.cards), '--image-bytes', String(options.imageBytes), '--card-bytes', String(options.cardBytes));
            break;
        case 'chats': case 'chats-large':
            scaleArgs.push('--chats', String(options.chats), '--chat-bytes', String(options.chatBytes));
            break;
        case 'worlds':
            scaleArgs.push('--worlds', String(options.worlds), '--world-bytes', String(options.worldBytes));
            break;
        default: break;
    }

    const artifact = {
        harness: 'tools/perf/a19-boot.mjs',
        environment: {
            git: gitFacts(),
            go: (spawnSync('go', ['version'], { encoding: 'utf8' }).stdout ?? '').trim(),
            node: process.version,
            os: { platform: process.platform, arch: process.arch, release: os.release() },
            cpu: { model: os.cpus()[0]?.model ?? null, logicalCores: os.cpus().length },
            totalRamBytes: os.totalmem(),
            gomaxprocsEnv: process.env.GOMAXPROCS ?? null,
            loadLabel: options.loadLabel,
            cpuLoadPercentStart: await cpuLoadOver(500),
        },
        subject: { path: options.binary, sha256: sha256File(options.binary), sizeBytes: fs.statSync(options.binary).size, version: binaryVersion(options.binary) },
        parameters: { ...options, binary: undefined, procstat: undefined, fixturegen: undefined },
        tree: { scale: options.scale, scaleArgs, generated: null, rounds: [] },
        rounds: [],
        summary: null,
        notes: [
            'Absolute milliseconds on this shared development host are comparable only WITHIN one run; loadLabel and the sampled CPU-load series are recorded.',
            'Peak RSS is procstat PeakWorkingSetSize (Windows) / VmHWM (Linux); no B/op value is ever reported as RSS.',
            'Windows stop is abrupt (TerminateProcess after child.kill); Windows cannot deliver SIGTERM to a console process.',
            'Go allocation totals are not observable from outside the process; ns/op, B/op and allocs/op come from internal/server/bench_test.go.',
        ],
    };

    const roundRecords = [];
    for (let round = 1; round <= options.rounds; round += 1) {
        const treeParent = path.join(options.workDir, 'trees', `${options.scale}-r${round}-${stamp}`);
        if (fs.existsSync(treeParent)) await fsp.rm(treeParent, { recursive: true, force: true });
        await fsp.mkdir(treeParent, { recursive: true });
        const generated = spawnSync(options.fixturegen, ['--out', treeParent, '--scale', options.scale, ...scaleArgs], { encoding: 'utf8' });
        if (generated.status !== 0) throw new Error(`fixturegen failed: ${generated.stderr}`);
        const summary = JSON.parse(generated.stdout.trim().split('\n').pop());
        artifact.tree.rounds.push({ round, generated: summary });
        if (!artifact.tree.generated) artifact.tree.generated = summary;
        const tree = { dataRoot: path.join(treeParent, 'data'), configPath: path.join(treeParent, 'config.yaml') };

        const cold = await measureBoot(tree, 'cold', round);
        const warm = await measureBoot(tree, 'warm', round);
        const row = { round, cold, warm };
        roundRecords.push(row);
        artifact.rounds.push({
            round,
            coldBootMs: cold.bootMs,
            warmBootMs: warm.bootMs,
            coldReady: cold.readySample,
            coldFinal: cold.finalSample,
            warmReady: warm.readySample,
            coldRequests: cold.requests,
            warmRequests: warm.requests,
            errors: [cold.error, warm.error].filter(Boolean),
        });
        console.log(`round ${round}: cold ${cold.bootMs === null ? 'FAILED' : `${cold.bootMs.toFixed(1)} ms`}, warm ${warm.bootMs === null ? 'FAILED' : `${warm.bootMs.toFixed(1)} ms`}`);
        if (!options.keepTrees) await fsp.rm(treeParent, { recursive: true, force: true });
    }

    const bootSeries = key => roundRecords.map(row => row[key]?.bootMs).filter(value => typeof value === 'number');
    const requestSeries = key => roundRecords.flatMap(row => (row[key]?.requests ?? []).map(request => request));
    const routeSummary = requests => ({
        cold: requests.filter(request => request.cache === 'cold').map(request => ({ ms: request.ms, status: request.status, bytes: request.bytes })),
        warmMs: summarise(requests.filter(request => request.cache === 'warm').map(request => request.ms)),
        statuses: [...new Set(requests.map(request => request.status))],
    });
    artifact.summary = {
        coldBootMs: summarise(bootSeries('cold')),
        warmBootMs: summarise(bootSeries('warm')),
        coldRuntime: routeSummary(requestSeries('cold')),
        warmRuntime: routeSummary(requestSeries('warm')),
        coldPeakRssBytes: roundRecords.map(row => row.cold?.finalSample?.peakRssBytes).filter(value => typeof value === 'number'),
        warmSteadyRssBytes: roundRecords.map(row => row.warm?.readySample?.rssBytes).filter(value => typeof value === 'number'),
        cpuLoadPercentEnd: await cpuLoadOver(500),
    };
    await fsp.mkdir(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, `${JSON.stringify(artifact, null, 2)}\n`, 'utf8');
    console.log(`artifact: ${out}`);
    const failures = artifact.rounds.flatMap(row => row.errors);
    if (failures.length) { console.error(`failures: ${failures.join(' | ')}`); return 1; }
    return 0;
}

main().then(code => process.exit(code)).catch(error => { console.error(`a19-boot: ${error.stack ?? error}`); process.exit(1); });
